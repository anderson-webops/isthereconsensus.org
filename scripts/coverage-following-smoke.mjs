import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import mongoose from "mongoose";
import { Claim } from "../back-end/dist/models/schemas/Claim.js";
import { ClaimSource } from "../back-end/dist/models/schemas/ClaimSource.js";
import { CoverageRequest } from "../back-end/dist/models/schemas/CoverageRequest.js";
import { ReaderLibrary } from "../back-end/dist/models/schemas/ReaderLibrary.js";

export async function checkCoverageFollowing({ api: requestApi, browser, base, review, userCookie, adminCookie, browserLogin, clickText, browserText, restartBackend }) {
	const api = (path, options = {}) => requestApi(path, { retryRateLimit: true, ...options });
	const empty = { savedReviewIds: [], followedTopicIds: [], savedComparisonSlugs: [], followedCoverageRequestIds: [] };
	const originalUser = (await api("/library/account", { cookie: userCookie })).data;
	const originalAdmin = (await api("/library/account", { cookie: adminCookie })).data;
	const fixtureId = new mongoose.Types.ObjectId();
	const sources = await ClaimSource.find({ claim: review._id }).lean();
	await Claim.create({ ...review, _id: fixtureId, topic: review.topic._id, slug: `following-fixture-${randomUUID()}`, status: "draft", publishedAt: undefined, readerUpdates: [], __v: 0 });
	const sourceCopies = sources.map(source => ({ ...source, _id: new mongoose.Types.ObjectId(), claim: fixtureId }));
	await ClaimSource.insertMany(sourceCopies);
	const draft = { title: "A public question for the requested-answer workflow", summary: "A separately approved, nonsensitive fixture scope for following editorial progress and an available reviewed answer.", status: "planned", topicId: null, claimId: null, privateNote: "PRIVATE FOLLOWING AUDIT MUST NEVER LEAK" };
	const created = (await api("/admin/coverage", { method: "POST", cookie: adminCookie, body: draft, status: 201 })).data.row;
	const requestId = created._id;
	const selection = { ...empty, followedCoverageRequestIds: [requestId], includeCoverageRequests: true };
	const feed = async (body = selection) => (await api("/library/updates", { method: "POST", body })).data;
	const resolve = async () => (await api("/library/resolve", { method: "POST", body: { ...empty, followedCoverageRequestIds: [requestId] } })).data;
	const saveUser = async (fields) => {
		const current = (await api("/library/account", { cookie: userCookie })).data;
		return api("/library/account", { method: "PATCH", cookie: userCookie, body: { ...current, ...fields } });
	};
	let revision = 0;
	const change = async (fields = {}) => {
		const row = (await api(`/admin/coverage/${requestId}`, { method: "PATCH", cookie: adminCookie, body: { ...draft, revision, operation: "save", publicSummaryApproved: true, publicUpdateSummary: "Approved progress for a requested research question.", ...fields } })).data.row;
		revision = row.revision;
		return row;
	};
	const context = await browser.createBrowserContext();
	const page = await context.newPage();
	const errors = [];
	page.on("pageerror", error => errors.push(error.message));
	let legacyId;
	try {
		assert.deepEqual((await resolve()).coverageRequests, []);
		assert.deepEqual((await feed()).updates, []);
		await api("/library/account", { method: "PATCH", body: { ...empty, revision: 0 }, status: 403 });
		await api("/library/account", { method: "PATCH", cookie: userCookie, body: { ...originalUser, followedCoverageRequestIds: [requestId] }, status: 422 });
		const first = await change({ operation: "approve" });
		const firstId = first.publicHistory[0].id;
		assert.match(firstId, /^[a-f\d-]{36}$/);
		const unchanged = await change({ privateNote: "PRIVATE DIFFERENT AUDIT NOTE WITHOUT PUBLIC PROGRESS" });
		assert.equal(unchanged.publicHistory.length, 1);
		assert.equal(unchanged.publicHistory[0].id, firstId);
		assert.equal(unchanged.publicUpdatedAt, first.publicUpdatedAt);
		await saveUser({ followedCoverageRequestIds: [requestId] });
		const account = (await api("/library/account", { cookie: userCookie })).data;
		const { followedCoverageRequestIds: _requests, ...legacyBody } = account;
		assert.deepEqual((await api("/library/account", { method: "PATCH", cookie: userCookie, body: legacyBody })).data.followedCoverageRequestIds, [requestId]);
		await api("/library/account", { method: "PATCH", cookie: userCookie, body: account, status: 409 });
		assert.deepEqual((await api("/library/account", { cookie: adminCookie })).data, originalAdmin);
		const librariesBeforeRead = await ReaderLibrary.countDocuments();
		assert.equal((await resolve()).coverageRequests[0]._id, requestId);
		assert.equal(await ReaderLibrary.countDocuments(), librariesBeforeRead);
		for (const values of [[requestId, requestId], ["PRIVATE QUESTION"], Array.from({ length: 101 }, (_, index) => index.toString(16).padStart(24, "0"))]) await api("/library/resolve", { method: "POST", body: { ...empty, followedCoverageRequestIds: values }, status: 400 });
		await page.goto(`${base}/roadmap/${requestId}`, { waitUntil: "networkidle0" });
		await page.waitForFunction(() => {
			const button = document.querySelector('.coverage-follow button');
			return button && !button.disabled;
		});
		await clickText(page, "Follow question");
		await browserText(page, "Saved in this browser.");
		await page.reload({ waitUntil: "networkidle0" });
		await page.waitForSelector('.coverage-follow button[aria-pressed="true"]');
		const stored = await page.evaluate(() => localStorage.getItem("consensus-reader-library-v1"));
		assert.deepEqual(JSON.parse(stored).followedCoverageRequestIds, [requestId]);
		assert.doesNotMatch(stored, /public question|PRIVATE|password|session|cookie|authorization/);
		await page.goto(`${base}/library`, { waitUntil: "networkidle0" });
		await browserText(page, draft.title);
		await change({ status: "researching", publicUpdateSummary: "Research is underway with a bounded source assessment." });
		await clickText(page, "Refresh updates");
		await browserText(page, "Research is underway with a bounded source assessment.");
		const publication = `/editorial/claims/${fixtureId}`;
		await api(`${publication}/publish`, { method: "POST", cookie: adminCookie, body: { revisionNote: "Initial owned following-workflow fixture publication" } });
		const publishedFields = { status: "published", claimId: String(fixtureId), topicId: String(review.topic._id), publicUpdateSummary: "An available sourced answer is now linked to this question." };
		await change(publishedFields);
		const initialFeed = await feed();
		assert.ok(initialFeed.updates.some(update => update.kind === "requested_answer"));
		assert.ok(initialFeed.updates.some(update => update.kind === "new_review" && update.review._id === String(fixtureId)));
		assert.deepEqual((await feed({ ...selection, includeCoverageRequests: false })).updates, []);
		assert.doesNotMatch(JSON.stringify(initialFeed), /PRIVATE|privateNote|feedbackId|audit|adminId|reviewedBy|sessionVersion/);
		await api(`${publication}/request-update`, { method: "POST", cookie: adminCookie, body: { revisionNote: "PRIVATE DRAFT FOLLOWING PREPARATION" } });
		assert.equal((await resolve()).coverageRequests[0].answerUnavailable, true);
		assert.ok((await feed()).updates.every(update => update.kind === "coverage_progress"));
		await api(`${publication}/publish`, { method: "POST", cookie: adminCookie, body: { revisionNote: "Owned subsequent substantive reader update", readerUpdateKind: "evidence_update", bottomLineImpact: "unchanged" } });
		assert.ok((await feed()).updates.some(update => update.kind === "evidence_update" && update.review._id === String(fixtureId)));
		await ClaimSource.deleteMany({ claim: fixtureId });
		assert.equal((await resolve()).coverageRequests[0].answerUnavailable, true);
		assert.ok((await feed()).updates.every(update => update.kind === "coverage_progress"));
		await ClaimSource.insertMany(sourceCopies);
		const stable = (await feed()).updates.map(update => [update.id, update.date]);
		await restartBackend();
		assert.deepEqual((await feed()).updates.map(update => [update.id, update.date]), stable);
		await clickText(page, "Refresh updates");
		await browserText(page, "An available sourced answer is now linked to this question.");
		await browserLogin(page);
		await page.goto(`${base}/library`, { waitUntil: "networkidle0" });
		await clickText(page, "Copy browser saves and follows to my account");
		await browserText(page, "Saved to your account.");
		assert.ok((await api("/library/account", { cookie: adminCookie })).data.followedCoverageRequestIds.includes(requestId));
		const require = createRequire(import.meta.url);
		for (const mode of ["light", "dark"]) {
			await page.evaluate(mode => localStorage.setItem("nuxt-color-mode", mode), mode);
			await page.reload({ waitUntil: "networkidle0" });
			await browserText(page, draft.title);
			await page.addStyleTag({ content: "*, *::before, *::after { animation: none !important; transition: none !important; }" });
			await page.setViewport({ width: 320, height: 900 });
			await page.evaluate(() => { document.documentElement.style.fontSize = "200%"; });
			await page.addScriptTag({ path: require.resolve("axe-core/axe.min.js") });
			assert.deepEqual((await page.evaluate(async () => (await window.axe.run(document, { runOnly: { type: "tag", values: ["wcag2a", "wcag2aa", "wcag21aa"] } })).violations)).map(item => ({ id: item.id, targets: item.nodes.map(node => node.target) })), []);
			assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
			await page.screenshot({ path: `/tmp/consensus-following-library-${mode}.png`, fullPage: true });
		}
		await change({ ...publishedFields, operation: "withdraw", title: "PRIVATE WITHDRAWN QUESTION TITLE", summary: "PRIVATE WITHDRAWN SUMMARY MUST NEVER APPEAR IN A LIBRARY OR UPDATE RESPONSE", publicSummaryApproved: false, publicUpdateSummary: "" });
		assert.deepEqual((await resolve()).coverageRequests, []);
		assert.deepEqual((await feed()).updates, []);
		await page.evaluate(async () => { await fetch("/api/auth/logout", { method: "POST" }); });
		await page.goto(`${base}/library`, { waitUntil: "networkidle0" });
		await browserText(page, "Requested question currently unavailable");
		assert.doesNotMatch(await page.evaluate(() => document.body.innerText), /PRIVATE|public question for the requested-answer/);
		await page.click('#followed-questions button');
		await browserText(page, "Choose “Follow question”");
		await saveUser({ followedCoverageRequestIds: [] });
		const removed = (await api("/library/account", { cookie: userCookie })).data;
		await api("/library/account", { method: "PATCH", cookie: userCookie, body: { ...removed, followedCoverageRequestIds: [requestId] }, status: 422 });
		const date = new Date(Date.now() - 2000);
		const legacy = await CoverageRequest.create({ title: "Legacy approved progress pagination fixture", summary: draft.summary, status: "researching", visibility: "public", publicUpdatedAt: date, publicHistory: Array.from({ length: 64 }, (_, index) => ({ date, status: "researching", summary: `Separately approved public legacy progress number ${index}.` })) });
		legacyId = legacy._id;
		const pagedSelection = { ...empty, followedCoverageRequestIds: [String(legacyId)], includeCoverageRequests: true };
		const firstPage = await feed(pagedSelection);
		await CoverageRequest.updateOne({ _id: legacyId }, { $push: { publicHistory: { id: randomUUID(), date: new Date(Date.now() + 60_000), status: "researching", summary: "A later event outside the frozen feed window." } } });
		const secondPage = await feed({ ...pagedSelection, cursor: firstPage.nextCursor });
		const thirdPage = await feed({ ...pagedSelection, cursor: secondPage.nextCursor });
		assert.deepEqual([firstPage.updates.length, secondPage.updates.length, thirdPage.updates.length], [30, 30, 4]);
		assert.equal(new Set([...firstPage.updates, ...secondPage.updates, ...thirdPage.updates].map(update => update.id)).size, 64);
		assert.equal(thirdPage.nextCursor, null);
		assert.equal((await CoverageRequest.findById(legacyId).lean()).publicHistory.filter(event => event.id).length, 1, "Reading legacy events must not rewrite database history.");
		assert.deepEqual(errors, []);
	} finally {
		await context.close();
		for (const [cookie, original] of [[userCookie, originalUser], [adminCookie, originalAdmin]]) {
			const current = (await api("/library/account", { cookie })).data;
			await api("/library/account", { method: "PATCH", cookie, body: { ...original, revision: current.revision } });
		}
		await CoverageRequest.deleteMany({ _id: { $in: [requestId, ...(legacyId ? [legacyId] : [])] } });
		await ClaimSource.deleteMany({ claim: fixtureId });
		await Claim.deleteOne({ _id: fixtureId });
	}
	console.log("requested-question following: legacy storage/account compatibility, approved progress, authenticated answer publication and subsequent evidence updates, source readiness, account isolation, restart-stable IDs, withdrawn privacy/removal, 64 tied legacy events and both-theme mobile/200% text accessibility passed");
}
